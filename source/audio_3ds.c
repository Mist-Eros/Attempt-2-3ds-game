void audio_set_muted(bool muted)
{
    s_muted = muted;
    if (!s_enabled)
        return;

    if (muted) {
        ndspChnSetPaused(MUSIC_CHANNEL, true);
        ndspChnSetPaused(MUSIC_CHANNEL_SPARE, true);
        sfx_stop_all();
    } else {
        int i;

        ndspChnSetPaused(MUSIC_CHANNEL, false);
        ndspChnSetPaused(MUSIC_CHANNEL_SPARE, false);
        for (i = 0; i < SFX_CHANNEL_COUNT; i++)
            ndspChnSetPaused(SFX_CHANNEL_FIRST + i, false);
    }
}

bool audio_is_muted(void)
{
    return s_muted;
}
